import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validate, worldFormats} from '../lib/validate.mjs';

// World format 0.11 (draft: panorama skies, builder worlds, object format 0.11 assets),
// builder/project.json (projectVersion 0.1) and IPC 0.27's builder state (RFC-0014 phase C).
const read=path=>JSON.parse(readFileSync(new URL(`../${path}`,import.meta.url)));
const pose={position:[0,0,0],rotation:[0,0,0,1]};
const ATMOSPHERE={fog:{color:[.028,.045,.065],density:.008,heightFalloff:0,baseHeight:0,excludeUnlit:true},
 sky:{zenith:[.18,.3,.52],horizon:[.55,.61,.65],ground:[.055,.07,.085],sun:{direction:[.3,1,.5],color:[1,.83,.6],intensity:3,angularRadius:.025}},
 exposure:1,toneMapping:'aces',bloom:{strength:.12,threshold:1,radius:3}};
const world=(over={})=>({formatVersion:'0.11',id:'local.harbour-plaza',version:'0.1.0',name:'Harbour plaza',license:'CC0-1.0',scene:'scene.gltf',
 defaultSpawn:'arrival',spawns:[{id:'arrival',pose}],attribution:[{path:'.',author:'Ada',license:'CC0-1.0'}],
 atmosphere:{...ATMOSPHERE,panorama:{image:'sky/panorama.jpg',projection:'equirect'}},...over});
const errors=(doc,options)=>validate('world',doc,undefined,doc.formatVersion,options).errors;

test('world 0.11 is a discovered world format and takes a panorama sky',()=>{
 assert.ok(worldFormats.includes('0.11'));assert.ok(!worldFormats.includes('0.10'));
 assert.deepEqual(errors(world()),[]);
 const sky=ATMOSPHERE;
 {
  assert.deepEqual(errors(world({atmosphere:{...sky,panorama:{image:'sky/p.jpg',projection:'equirect',encoding:'srgb',intensity:1,rotation:1.2,maxResolution:1024,environment:true}}})),[]);
  for(const bad of [{image:'sky/p.jpg'},{image:'sky/p.jpg',projection:'cube'},{image:'/abs.jpg',projection:'equirect'},{image:'sky/p.jpg',projection:'equirect',maxResolution:4096},{image:'sky/p.jpg',projection:'equirect',extra:1}])
   assert.notDeepEqual(errors(world({atmosphere:{...sky,panorama:bad}})),[],JSON.stringify(bad));
  assert.notDeepEqual(errors({...world({atmosphere:{...sky,panorama:{image:'sky/p.jpg',projection:'equirect'}}}),formatVersion:'0.9'}),[],'0.9 has no panorama');
  assert.deepEqual(errors({...world({atmosphere:sky}),formatVersion:'0.9'}),[]);
 }
});

test('world 0.11 takes object format 0.11 assets (screens, imports); movers stay reserved',()=>{
 const screen=read('examples/object-screen.json');
 const w=world({atmosphere:undefined,objectAssets:[{id:'screen',dir:'objects/workspace-screen-wall'}],objects:[{id:'u-7c2e91',asset:'screen',pose,locked:true}]});
 delete w.atmosphere;
 assert.deepEqual(errors(w,{assets:{screen}}),[]);
 const old={...w,formatVersion:'0.9'};
 assert.ok(errors(old,{assets:{screen}}).some(e=>e.includes('object format 0.11 is newer than the world\'s 0.9')),JSON.stringify(errors(old,{assets:{screen}})));
 const inline={...w,objectAssets:[{id:'tram',scene:'tram.glb',traits:{mover:{speed:1}}}],objects:[]};
 assert.ok(errors(inline).some(e=>e.includes('traits.mover: reserved')),JSON.stringify(errors(inline)));
});

const project=(over={})=>({projectVersion:'0.1',id:'local.harbour-plaza',name:'Harbour plaza',starter:'flat-land@0.1',base:'builder/base.json',
 sky:{image:'sky/panorama.jpg',license:'CC0-1.0',author:'Hyprune contributors',source:'generated by the flat-land starter'},
 placements:[{id:'u-7c2e91',ref:'world/barrel',pose,scale:1},{id:'u-000001',ref:'world/workspace-screen-wall-16x9',pose,scale:1,workspace:25,locked:true}],...over});

test('builder/project.json: closed shape, world refs, unique ids and workspaces',()=>{
 assert.deepEqual(validate('project',project()).errors,[]);
 assert.deepEqual(validate('project',project({placements:[],sky:{image:null,license:'LicenseRef-unknown',author:'unknown',source:'unknown'}})).errors,[]);
 for(const bad of [{projectVersion:'0.2'},{starter:'desert@0.1'},{extra:1},{placements:[{id:'u-1',ref:'world/x',pose,scale:1}]},
  {placements:[{id:'u-000001',ref:'user/barrel',pose,scale:1}]},{placements:Array(129).fill({id:'u-000001',ref:'world/x',pose,scale:1})}])
  assert.equal(validate('project',project(bad)).valid,false,JSON.stringify(bad));
 assert.ok(validate('project',project({placements:[{id:'u-000001',ref:'world/x',pose,scale:1},{id:'u-000001',ref:'world/y',pose,scale:1}]})).errors.some(e=>e.includes('duplicate id')));
 assert.ok(validate('project',project({placements:[{id:'u-000001',ref:'world/x',pose,scale:1,workspace:25},{id:'u-000002',ref:'world/y',pose,scale:1,workspace:25}]})).errors.some(e=>e.includes('another screen')));
 assert.ok(validate('project',project({sky:{image:null,license:'Bogus 9',author:'a',source:'b'}})).errors.some(e=>e.startsWith('sky.license')));
});

test('IPC 0.27 builder state: required, null or the loaded world folder; world/<id> refs and catalog source',()=>{
 const delta=changes=>validate('ipc',{jsonrpc:'2.0',method:'state.delta',params:{subscriptionId:'sub',sessionId:'s',baseRevision:1,revision:2,changes}},undefined,'0.27').valid;
 const b={projectId:'harbour-plaza',worldId:'local.harbour-plaza',name:'Harbour plaza',folder:'/home/u/.local/share/hyprune/projects/harbour-plaza',
  mode:'edit',revision:3,placements:2,sky:'/home/u/.local/share/hyprune/projects/harbour-plaza/sky/panorama.jpg',error:null};
 assert.ok(delta({builder:b}));assert.ok(delta({builder:null}));
 for(const bad of [{...b,mode:'play'},{...b,folder:'relative'},{...b,placements:129},{...b,extra:1}])assert.ok(!delta({builder:bad}),JSON.stringify(bad));
 assert.ok(!validate('ipc',{jsonrpc:'2.0',method:'state.delta',params:{subscriptionId:'sub',sessionId:'s',baseRevision:1,revision:2,changes:{builder:b}}},undefined,'0.26').valid);
 const ok=(m,p)=>validate('ipc',{jsonrpc:'2.0',id:'b',method:m,params:p},undefined,'0.27').valid;
 assert.ok(ok('objects.place',{ref:'world/barrel'}));assert.ok(ok('objects.pocket',{ref:'world/workspace-screen-wall-16x9'}));
 assert.ok(!validate('ipc',{jsonrpc:'2.0',id:'b',method:'objects.place',params:{ref:'world/barrel'}},undefined,'0.26').valid);
});
